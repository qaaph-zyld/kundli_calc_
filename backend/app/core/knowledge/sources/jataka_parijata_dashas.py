def get_dasha_interpretation(planet: str) -> Dict[str, Any]:
    """
    Get Jataka Parijata interpretation for planetary dasha.

    Args:
        planet: Planet name

    Returns:
        Dictionary with dasha interpretation data
    """
    return JATAKA_PARIJATA_DASHAS.get(planet, None)


def get_all_dasha_planets() -> list:
    """Get list of all planets with dasha interpretations"""
    return list(JATAKA_PARIJATA_DASHAS.keys())
